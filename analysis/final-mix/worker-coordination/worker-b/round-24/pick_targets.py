def load_layout():
    size, name = {}, {}
    with open(LTS, encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith("#"):
                continue
            p = line.rstrip("\n").split("\t")
            if len(p) < 3 or len(p[0]) != 8:
                continue
            try:
                size[p[0]] = int(p[2])
                name[p[0]] = p[3] if len(p) > 3 else ""
            except ValueError:
                pass
    return size, name


def load_pseudocode():
    jl = {}
    with open(JP, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                d = json.loads(line)
            except ValueError:
                continue
            a = str(d.get("address", "")).lower()
            if len(a) == 8:
                jl[a] = d
    return jl


def words(blob, address, n):
    off = address - MAIN_VADDR + MAIN_FOFF
    raw = blob[off:off + n * 4]
    return [int.from_bytes(raw[i:i + 4], "little") for i in range(0, len(raw), 4)]


def classify(ws):
    tags = []
    op0 = ws[0] >> 26
    # must open with a real frame push: addiu sp,sp,-N
    if not (op0 == 0x09 and ((ws[0] >> 16) & 0x1F) == 29 and (ws[0] & 0x8000)):
        return "skip", ["no-frame"]
    frame = (ws[0] & 0xFFFF)
    tags.append("frame=%d" % (0x10000 - frame))
    if not any(((w >> 26) in (0x3F, 0x37) and ((w >> 21) & 0x1F) == 29) for w in ws):
        return "skip", tags + ["no-stack-word"]
    for w in ws:
        op = w >> 26
        if op in (0x11, 0x12, 0x13, 0x31, 0x35, 0x39, 0x3D):
            return "skip", tags + ["cop1"]
        if op == 0x2D:
            return "skip", tags + ["premul"]
        if op == 0x01 and ((w >> 16) & 0x1F) in (0, 1):
            return "skip", tags + ["bltz"]
    # round 14: drop the two classes proven unreachable on this compiler.
    #   jalr through a loaded entry  -> the `jalr $v0` class (9 members, 6 variants each)
    #   sd s8 without sd ra         -> the leaf frame-pointer idiom (002b99a0, 002b6ab8, 002b81ec)
    # sd/ld encode the BASE in rs (sp = 29) and the SAVED REGISTER in rt (ra = 31)
    has_ra_save = any((w >> 26) == 0x3F and ((w >> 21) & 0x1F) == 29 and ((w >> 16) & 0x1F) == 31
                      for w in ws)
    if not has_ra_save:
        return "skip", tags + ["no-ra-save"]
    for w in ws:
        if w >> 26 == 0 and (w & 0x3F) == 0x09:
            return "skip", tags + ["jalr-loaded-entry"]
    # round 20: the frame-pointer class grew to 19 members once the wrappers that
    # save BOTH s8 and ra turned up (round 20 scored 0/16 on fifteen of them).
    # sd s8 = op 0x3f, base sp in rs (29), saved register in rt (30 = s8).
    for w in ws:
        if (w >> 26) == 0x3F and ((w >> 21) & 0x1F) == 29 and ((w >> 16) & 0x1F) == 30:
            return "skip", tags + ["frame-pointer-s8"]
    # round 21: GCC 3.2 will not if-convert a predicate into movz/movn, and the
    # quad lq/sq struct-copy class keeps landing in a different temp (0016e200,
    # 00165830, 001906f0, 002cb7c8, 002dd790). Both documented; skip them.
    for w in ws:
        if (w >> 26) == 0 and (w & 0x3F) in (0x0A, 0x0B):
            return "skip", tags + ["movz-movn"]
        if (w >> 26) in (0x1E, 0x1F):
            return "skip", tags + ["lq-sq-quad"]
    # round 22: GCC 3.2 emits three or more consecutive same-base stores in reverse
    # offset order and ignores volatile on them (002e5f70, 0019da20, 002c1a58 - 5, 5
    # and 8 variants tried, none produced the target order).
    run = 0
    last = None
    for w in ws:
        op = w >> 26
        if op in (0x28, 0x29, 0x2F, 0x3F):        # sw / sh / sd / swc
            base, off = (w >> 21) & 0x1F, w & 0xFFFF
            key = (base, off)
        elif op == 0x20:                            # lb
            key = ((w >> 21) & 0x1F, w & 0xFFFF)
        elif op == 0x24:                            # lh
            key = ((w >> 21) & 0x1F, w & 0xFFFF)
        elif op == 0x2C:                            # lw
            key = ((w >> 21) & 0x1F, w & 0xFFFF)
        else:
            key = None
        if key is not None and key == last:
            run += 1
            if run >= 2:
                return "skip", tags + ["store-run-reorder"]
        else:
            run = 0
        last = key
    ncall = sum(1 for w in ws if (w >> 26) == 0x03)
    njump = sum(1 for w in ws if (w >> 26) in (0x02, 0x05))
    tags.append("call=%d" % ncall)
    tags.append("br=%d" % njump)
    if njump == 0:
        tags.append("NO-BRANCH")
    return "keep", tags


def main():
    reg = load_registration()
    size, name = load_layout()
    jl = load_pseudocode()
    print("registered rows:", len(reg), " layout ranges:", len(size), " pseudocode:", len(jl))
    blob = open(ISO, "rb").read()
    taken = reg | ATTEMPTED | RESERVED | load_primary_reserved()
    cands = [a for a in jl if a not in taken and a in size]
    keep = []
    for a in cands:
        n = size[a]
        if n % 4 or n < 20 or n > 120:
            continue
        verdict, tags = classify(words(blob, int(a, 16), n // 4))
        if verdict == "keep":
            keep.append((n, a, tags))
    keep.sort(key=lambda e: (0 if "NO-BRANCH" in e[2] else 1, e[0], e[1]))
    print("candidates after screening:", len(keep))
    print()
    for n, a, tags in keep[:int(sys.argv[1]) if len(sys.argv) > 1 else 30]:
        d = jl[a]
        body = " ".join(str(d.get("code") or d.get("body") or "").split())
        print("%s %4dB %-26s %s" % (a, n, name.get(a, "")[:26], ",".join(tags)))
        print("      sig : %s" % d.get("signature", "")[:110])
        print("      code: %s" % body[:300])
    print()
    print("tags:", Counter(t for _, _, ts in keep for t in ts).most_common(12))


if __name__ == "__main__":
    main()